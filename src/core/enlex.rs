/// 词典按中文长度降序（长句优先，防止子串抢答）
fn lex_sorted() -> &'static Vec<(&'static str, &'static str)> {
    static SORTED: OnceLock<Vec<(&'static str, &'static str)>> = OnceLock::new();
    SORTED.get_or_init(|| {
        let mut v: Vec<(&str, &str)> = LEX.to_vec();
        v.sort_by(|a, b| b.0.chars().count().cmp(&a.0.chars().count()));
        v
    })
}

/// 中文正文 html → 英文正文 html（词条 + 全角标点归一）
pub fn translate_en(html: &str) -> String {
    translate_en_with(html, &[])
}

/// 带专名保护：`keep` 中的字符串（如工程名称）在翻译期间以哨兵占位，
/// 译后原样还原——防止名称中的「蛋鸭/肉鸡」等育种词被词条误替换
pub fn translate_en_with(html: &str, keep: &[&str]) -> String {
    let mut s = html.to_string();
    let mut guards: Vec<(String, &str)> = Vec::new();
    for (i, k) in keep.iter().enumerate() {
        if !k.is_empty() && s.contains(k) {
            let tok = format!("\u{1}K{i}\u{1}");
            s = s.replace(k, &tok);
            guards.push((tok, k));
        }
    }
    for (cn, en) in lex_sorted() {
        if s.contains(cn) {
            s = s.replace(cn, en);
        }
    }
    // 全角标点 → 半角（词条未覆盖的残段兜底）
    for (a, b) in [
        ("（", " ("),
        ("）", ")"),
        ("；", "; "),
        ("，", ", "),
        ("。", ". "),
        ("：", ": "),
        ("／", "/"),
        ("＝", "="),
        ("、", ", "),
        ("＋", "+"),
        ("——", " — "),
        ("→", " -> "),
    ] {
        s = s.replace(a, b);
    }
    // 比较符统一转 HTML 实体——译文若含裸 < >，docx tokenizer 会当标签起点吞掉后文
    s = s.replace("<=", "&lt;=").replace(">=", "&gt;=");
    s = s.replace(": :", ":");
    // 行业记法：℃ → °C、除号 ÷ → /
    s = s.replace('℃', "°C").replace('÷', " / ");
    // 还原专名哨兵
    for (tok, k) in guards.iter().rev() {
        s = s.replace(tok, k);
    }
    s
}

/// 残留中文检测（迭代补词条用）
pub fn leftover_cjk(s: &str) -> Vec<String> {
    let mut set = std::collections::BTreeSet::new();
    let mut cur = String::new();
    for ch in s.chars() {
        if ('\u{4e00}'..='\u{9fff}').contains(&ch) || "（）：；，。、＝＋／".contains(ch)
        {
            cur.push(ch);
        } else {
            if !cur.is_empty() && cur.chars().any(|c| ('\u{4e00}'..='\u{9fff}').contains(&c)) {
                set.insert(cur.clone());
            }
            cur.clear();
        }
    }
    if !cur.is_empty() && cur.chars().any(|c| ('\u{4e00}'..='\u{9fff}').contains(&c)) {
        set.insert(cur);
    }
    set.into_iter().collect()
}
